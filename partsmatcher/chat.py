        "  rather than writing a guess. Never write unconfirmed photo entries.",
        "- On confirmation, write them like any other entry plus provenance",
        "  fields the schema tolerates: `\"source\": \"photo\"` and",
        "  `\"confidence\"` (0.0–1.0, your identification confidence — keep it",
        "  even after the user confirms). When a photo-detected part merges",
        "  into an existing entry, just sum the quantity; don't add",
        "  provenance fields to entries the user typed.",
        "- Alias records for photo entries use your visual description as",
        "  \"raw\" and add the photo filename:",
        "",
        '  {"raw": "blue axial resistor, 4-band", "name": "470 ohm resistor", "quantity": 25, "action": "photo", "photo": "bench.jpg", "confidence": 0.7}',
