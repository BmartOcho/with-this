"""Conversational mode: hand the inventory to the user's local Claude Code CLI.

PartsMatcher deliberately does NOT call the Anthropic API and needs no API
key. Instead it prepares a session workspace — a generated CLAUDE.md carrying
the parts inventory, the deterministic match report, and workbench-assistant
guidance, alongside copies of the raw JSON — and launches the `claude` binary
the user already has installed and logged in. Claude Code reads CLAUDE.md at
session start, so the chat opens already knowing exactly what the user owns,
and their existing subscription auth applies.

The deterministic matcher (`partsmatcher match`) stays fully offline and
never requires Claude to be installed.
"""

